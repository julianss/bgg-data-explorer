<div class="about card">
  <h2>About this tool</h2>

  <p>
    So here's the story: I'm taking the
    <a href="https://elvtr.com/course/board-game-production" target="_blank" rel="noopener">ELVTR</a>
    board game production course, and people kept asking "where can I check which
    mechanics are popular?" or "how do I see what's trending?" Main suggestions were
    "ask AI" and "browse BGG".
  </p>

  <p>
    So I did both! I downloaded a bunch of data from BoardGameGeek (about 30,000
    games worth) and used AI to build this little visualizer. Now
    instead of scrolling through endless BGG pages or hoping ChatGPT doesn't
    hallucinate a mechanic that doesn't exist, you can actually <em>see</em> the
    data; what mechanics people love, which combos show up together,
    what's trending, and where there might be room for something new.
  </p>

  <p>
    Sharing it here in case it's useful (or at least entertaining to click around) for my
    classmates and anyone else nerding out about board game design.
  </p>

  <p>May be somewhat confusing but hey it's more fun than a spreadsheet!</p>
</div>

